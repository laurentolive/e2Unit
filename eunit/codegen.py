"""Generation of the adapter table (eunit_suite.c) and of the build fragment (suite.mk)."""
from pathlib import Path

from . import __version__
from .spec import Suite


def _mk_path(p: Path) -> str:
    s = p.as_posix()
    if " " in s:
        raise ValueError(f"make cannot handle spaces in source paths: {s}")
    return s


def generate_c(suite: Suite) -> str:
    lines = [
        f"/* Generated by e2Unit {__version__} from {suite.path.name} - do not edit */",
        "/* SPDX-License-Identifier: MIT */",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        '#include "eunit.h"',
    ]
    lines += [f'#include "{h}"' for h in suite.headers]
    lines += ["", "/* Prototypes from the specification (checked against the headers) */"]
    for f in suite.function_list():
        if not f.custom:
            ret = f.outputs[0].dtype.name if f.has_return else "void"
            args = ", ".join(f"{p.dtype.name} {p.name}" for p in f.inputs) or "void"
            lines.append(f"{ret} {f.c_name}({args});")

    custom = [f for f in suite.function_list() if f.custom]
    if custom:
        lines += ["", "/* Custom adapters, implemented with EUNIT_ADAPTER(name) */"]
        lines += [f"EUNIT_ADAPTER({f.name});" for f in custom]

    for f in suite.function_list():
        if f.custom:
            continue
        lines += ["", f"/* {f.prototype} */",
                  f"static void eunit_adapter_{f.name}(const int32_t *in, int32_t *out)", "{"]
        if not f.inputs:
            lines.append("    (void)in;")
        if not f.outputs:
            lines.append("    (void)out;")
        args = ", ".join(p.dtype.c_from_word(f"in[{i}]") for i, p in enumerate(f.inputs))
        call = f"{f.c_name}({args})"
        if f.has_return:
            lines.append(f"    out[0] = {f.outputs[0].dtype.c_to_word(call)};")
        else:
            lines.append(f"    {call};")
        lines.append("}")

    lines += ["", "const eunit_entry_t eunit_suite_table[] = {"]
    for f in suite.function_list():
        lines.append(f"    {{ eunit_adapter_{f.name}, {len(f.inputs)}u, {len(f.outputs)}u }}, "
                     f"/* {f.index}: {f.signature()} */")
    lines += ["};",
              f"const uint32_t eunit_suite_count = {len(suite.functions)}u;",
              f"const uint32_t eunit_suite_hash = 0x{suite.hash:08X}u;", ""]
    return "\n".join(lines)


def generate_mk(suite: Suite) -> str:
    def block(var, items):
        if not items:
            return f"{var} :=\n"
        return f"{var} := \\\n" + " \\\n".join(f"  {x}" for x in items) + "\n"

    return "".join([
        f"# Generated by e2Unit {__version__} from {suite.path.name} - do not edit\n",
        "# SPDX-License-Identifier: MIT\n",
        f"EUNIT_SUITE_NAME := {suite.name}\n",
        block("EUNIT_SUITE_SRCS", [_mk_path(p) for p in suite.sources]),
        block("EUNIT_SUITE_INCS", [_mk_path(p) for p in suite.includes]),
        block("EUNIT_SUITE_DEFS", [f"-D{d}" for d in suite.defines]),
        block("EUNIT_SUITE_DEPS", [_mk_path(p) for p in suite.files]),
    ])


def write(suite: Suite, out_dir) -> list:
    """Write the generated files, only touching them when the content changes."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, content in (("eunit_suite.c", generate_c(suite)), ("suite.mk", generate_mk(suite))):
        p = out / name
        if not p.exists() or p.read_text(encoding="utf-8") != content:
            p.write_text(content, encoding="utf-8", newline="\n")
        else:
            p.touch()
        written.append(p)
    return written
