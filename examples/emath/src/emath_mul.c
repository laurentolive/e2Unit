/*******************************************************************************
 * emath - Q15 multiplication
 ******************************************************************************/
#include "emath.h"

int16_t emath_mul_q15(int16_t a, int16_t b)
{
    int32_t p = ((int32_t)a * b + (1 << 14)) >> 15;  /* rounded to nearest */
    if (p > 32767) {
        p = 32767;                                    /* only (-1) * (-1) */
    }
    return (int16_t)p;
}
